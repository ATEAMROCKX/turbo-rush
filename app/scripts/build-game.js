// Builds game/gameHtml.js from the web game (../index.html) so the app runs fully offline.
// Run: npm run build:game   (do this after every change to index.html, before eas build / eas update)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, '..', 'index.html'), 'utf8');
const font = f => fs.readFileSync(path.join(root, 'game', 'fonts', f)).toString('base64');

const fontCss = `<style>
@font-face { font-family: "Bungee"; src: url(data:font/woff2;base64,${font('bungee-400.woff2')}) format("woff2"); font-weight: 400; font-display: block; }
@font-face { font-family: "Rubik"; src: url(data:font/woff2;base64,${font('rubik-500.woff2')}) format("woff2"); font-weight: 500; font-display: block; }
@font-face { font-family: "Rubik"; src: url(data:font/woff2;base64,${font('rubik-700.woff2')}) format("woff2"); font-weight: 700; font-display: block; }
/* feel like an app, not a web page */
* { -webkit-user-select: none; user-select: none; -webkit-touch-callout: none; -webkit-tap-highlight-color: transparent; }
input { -webkit-user-select: text; user-select: text; }
html, body { overscroll-behavior: none; }
</style>`;

let html = src
  .split('\n')
  .filter(l => !/fonts\.(googleapis|gstatic)\.com/.test(l))
  .join('\n');
if (/https?:\/\/(?!www\.w3\.org)/.test(html.replace(/<!--[\s\S]*?-->/g, ''))) {
  const hits = html.match(/https?:\/\/[^\s"'<>)]+/g).filter(u => !u.startsWith('http://www.w3.org'));
  if (hits.length) console.warn('Warning: game still references the internet:', [...new Set(hits)].join(', '));
}
html = html.replace('<title>', fontCss + '\n<title>');

fs.writeFileSync(
  path.join(root, 'game', 'gameHtml.js'),
  '// AUTO-GENERATED by scripts/build-game.js from ../index.html — do not edit by hand.\nexport default ' + JSON.stringify(html) + ';\n'
);
console.log(`game/gameHtml.js written (${Math.round(html.length / 1024)} KB)`);
